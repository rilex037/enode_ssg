/**
 * Post build step.
 *
 * 1. Inlines the compiled stylesheet into every prerendered HTML file, which
 *    removes the render-blocking CSS request and guarantees the first paint is
 *    already styled. Standalone CSS files are deleted afterwards.
 * 2. Writes a snapshot of the stylesheet to worker/generated/site-css.ts so
 *    the dynamic-page worker can render on-demand pages with the exact same
 *    styling as the prerendered ones.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, unlinkSync } from 'node:fs'
import { join, resolve } from 'node:path'

const dist = resolve(import.meta.dirname, '..', 'dist')

const htmlFiles = readdirSync(dist).filter((f) => f.endsWith('.html'))

let failed = false

// 1. Inline the stylesheet into each HTML file
const STYLESHEET_LINK = /<link\b[^>]*\brel="stylesheet"[^>]*>/g
const cssByFile = new Map()

for (const file of htmlFiles) {
  const path = join(dist, file)
  let html = readFileSync(path, 'utf-8')
  let css = ''

  html = html.replace(STYLESHEET_LINK, (tag) => {
    const href = tag.match(/href="([^"]+)"/)?.[1]
    // Keep external stylesheets (e.g. Google Fonts) untouched.
    if (!href || !href.startsWith('/')) return tag

    const cssPath = join(dist, href)
    if (!existsSync(cssPath)) return tag

    css += readFileSync(cssPath, 'utf-8')
    return ''
  })

  if (css) {
    html = html.replace('</head>', `<style>${css}</style></head>`)
    writeFileSync(path, html, 'utf-8')
    cssByFile.set(file, css)
  }
}


// 2. Delete the now-unused standalone CSS files
const assetsDir = join(dist, 'assets')
if (existsSync(assetsDir)) {
  for (const name of readdirSync(assetsDir)) {
    if (name.endsWith('.css')) {
      unlinkSync(join(assetsDir, name))
    }
  }
}

// 3. Make sure no JS references a deleted stylesheet
if (existsSync(assetsDir)) {
  const cssFiles = readdirSync(assetsDir).filter((n) => n.endsWith('.css'))
  for (const name of readdirSync(assetsDir)) {
    if (!name.endsWith('.js')) continue
    const js = readFileSync(join(assetsDir, name), 'utf-8')
    const orphans = cssFiles.filter((css) => js.includes(css))
    if (orphans.length) {
      console.error(`✗ ${name} still references deleted stylesheet(s): ${orphans.join(', ')}`)
      failed = true
    }
  }
}

// 4. Snapshot the stylesheet for the dynamic-page worker.
// The homepage is the layout baseline; per-route chunks differ from it only
// in route-specific rules, which dynamic pages never need.
{
  const snapshot =
    cssByFile.get('index.html') ??
    [...cssByFile.values()].reduce((a, b) => (b.length > a.length ? b : a), '')

  const generatedDir = resolve(import.meta.dirname, '..', 'worker', 'generated')
  mkdirSync(generatedDir, { recursive: true })
  writeFileSync(
    join(generatedDir, 'site-css.ts'),
    `// AUTO-GENERATED by scripts/postbuild.mjs — do not edit by hand.\n` +
      `// Snapshot of the site stylesheet, used by the worker to render dynamic\n` +
      `// pages with the exact same look as the prerendered static ones.\n` +
      `// Regenerated on every \`npm run build\`; empty on a fresh clone until then.\n` +
      `export const SITE_CSS = ${JSON.stringify(snapshot)}\n`,
    'utf-8',
  )
  console.log(`Site CSS snapshot written (${snapshot.length} bytes).`)
}

if (failed) {
  console.error('\nPost build checks failed.')
  process.exit(1)
}

console.log('\nPost build complete. CSS inlined into', htmlFiles.length, 'HTML file(s).')
